        redirect('admin/security-overview.php');
    }

    $action = $_POST['action'] ?? '';

    // Action: Trigger Instant Database Backup
    if ($action === 'create_backup') {
        $backupDir = __DIR__ . '/../database/backups';
        if (!is_dir($backupDir)) {
            mkdir($backupDir, 0755, true);
        }

        try {
            $tables = $db->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
            $timestamp = date('Y-m-d_H-i-s');
            $sql = "-- ApexVote Verified Database Backup\n-- Timestamp: " . date('Y-m-d H:i:s T') . "\n-- Generated by Admin #{$user['id']} ({$user['email']})\n\nSET FOREIGN_KEY_CHECKS=0;\n\n";

            foreach ($tables as $table) {
                $create = $db->query("SHOW CREATE TABLE `$table`")->fetch(PDO::FETCH_ASSOC);
                $sql .= "DROP TABLE IF EXISTS `$table`;\n" . $create['Create Table'] . ";\n\n";
                $rows = $db->query("SELECT * FROM `$table`")->fetchAll(PDO::FETCH_ASSOC);
                if (!empty($rows)) {
                    $cols = array_keys($rows[0]);
                    $colList = '`' . implode('`, `', $cols) . '`';
                    $sql .= "INSERT INTO `$table` ($colList) VALUES\n";
                    $valStrings = [];
                    foreach ($rows as $r) {
                        $vals = array_map(function($v) use ($db) {
                            if ($v === null) return 'NULL';
                            return $db->quote($v);
                        }, $r);
                        $valStrings[] = '(' . implode(', ', $vals) . ')';
                    }
                    $sql .= implode(",\n", $valStrings) . ";\n\n";
                }
            }
            $sql .= "SET FOREIGN_KEY_CHECKS=1;\n";

            $backupFilename = "backup_{$timestamp}.sql";
            $targetPath = $backupDir . '/' . $backupFilename;
            file_put_contents($targetPath, $sql);

            audit_log('DATABASE_BACKUP_CREATED', "Admin created verified database backup: {$backupFilename}", $user['id']);
            set_flash('success', "Verified database backup created successfully: {$backupFilename} (" . number_format(filesize($targetPath) / 1024, 1) . " KB)");
            redirect('admin/security-overview.php');
        } catch (Exception $e) {
            error_log("Backup creation error: " . $e->getMessage());
            set_flash('danger', "Database backup failed: " . $e->getMessage());
            redirect('admin/security-overview.php');
        }

    // Action: Test SMTP Connectivity
    } elseif ($action === 'test_smtp') {
        $testEmail = trim(filter_var($_POST['test_email'] ?? '', FILTER_SANITIZE_EMAIL));
        if (empty($testEmail) || !filter_var($testEmail, FILTER_VALIDATE_EMAIL)) {
            $testEmail = $user['email'];
        }

        if (!is_smtp_configured()) {
            $smtpTestResult = [
                'success' => false,
                'message' => 'Cannot test SMTP: Credentials are not configured in environment (.env).'
            ];
        } else {
            $dummyOtp = (string)random_int(100000, 999999);
            $res = send_vote_verification_email($testEmail, $user['full_name'], $dummyOtp);
            if ($res['success']) {
                $smtpTestResult = [
                    'success' => true,
                    'message' => "SMTP handshake succeeded! Test verification email was accepted by mail server for delivery to {$testEmail}."
                ];
                audit_log('SMTP_TEST_SUCCESS', "Admin tested SMTP delivery to {$testEmail}", $user['id']);
            } else {
                $smtpTestResult = [
                    'success' => false,
                    'message' => "SMTP connection failed: " . ($res['error'] ?? 'Handshake failed.')
                ];
                audit_log('SMTP_TEST_FAILED', "Admin SMTP test failed to {$testEmail}", $user['id']);
            }
        }
    }
